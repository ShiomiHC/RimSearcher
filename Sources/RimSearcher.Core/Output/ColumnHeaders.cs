    private static readonly HashSet<string> DataColumns = new(StringComparer.Ordinal) { "rows" };

    private static readonly AsyncLocal<List<string>?> Misses = new();

    public static string For(string block, string key)
    {
        if (ByBlock.TryGetValue(block, out var own) && own.TryGetValue(key, out var h)) return h;
        if (ByKey.TryGetValue(key, out h)) return h;
        if (!DataColumns.Contains(block)) Misses.Value?.Add($"{block}.{key}");
        return key;
    }

    public static List<string> StartCollecting()
    {
        var list = new List<string>();
        Misses.Value = list;
        return list;
    }
